import AppKit
import CryptoKit

enum ClipKind: String, Codable {
    case text, image
}

struct ClipItem: Codable, Identifiable, Equatable {
    var id = UUID()
    var kind: ClipKind
    var text: String?
    var imageFile: String?
    var imageHash: String?
    var imageSize: String?
    var date = Date()
    var pinned = false
    var sourceName: String?
    var sourceBundleID: String?

    var isLink: Bool {
        guard kind == .text, let t = text?.trimmingCharacters(in: .whitespacesAndNewlines) else { return false }
        guard t.hasPrefix("http://") || t.hasPrefix("https://") else { return false }
        return !t.contains(where: { $0.isWhitespace })
    }
}

@MainActor
final class ClipboardStore: ObservableObject {
    static let shared = ClipboardStore()

    static let minItems = 20
    static let maxItemsCap = 200

    @Published private(set) var items: [ClipItem] = []
    @Published var isPaused = false

    @Published var maxItems: Int {
        didSet {
            let clamped = min(max(maxItems, Self.minItems), Self.maxItemsCap)
            if clamped != maxItems { maxItems = clamped; return }
            UserDefaults.standard.set(maxItems, forKey: "maxItems")
            prune()
            save()
        }
    }

    private let pasteboard = NSPasteboard.general
    private var lastChangeCount: Int
    private var timer: Timer?

    private let ignoredTypes: [NSPasteboard.PasteboardType] = [
        .init("org.nspasteboard.ConcealedType"),
        .init("org.nspasteboard.TransientType"),
        .init("org.nspasteboard.AutoGeneratedType"),
        .init("com.agilebits.onepassword"),
    ]

    private let baseURL: URL = {
        let dir = FileManager.default.urls(for: .applicationSupportDirectory, in: .userDomainMask)[0]
            .appendingPathComponent("ClipStack", isDirectory: true)
        try? FileManager.default.createDirectory(at: dir.appendingPathComponent("images"), withIntermediateDirectories: true)
        return dir
    }()

    var imagesURL: URL { baseURL.appendingPathComponent("images", isDirectory: true) }
    private var historyURL: URL { baseURL.appendingPathComponent("history.json") }

    private init() {
        let saved = UserDefaults.standard.integer(forKey: "maxItems")
        maxItems = saved == 0 ? 50 : min(max(saved, Self.minItems), Self.maxItemsCap)
        lastChangeCount = NSPasteboard.general.changeCount
        load()
    }

    func start() {
        timer?.invalidate()
        let t = Timer(timeInterval: 0.4, repeats: true) { [weak self] _ in
            MainActor.assumeIsolated { self?.poll() }
        }
        RunLoop.main.add(t, forMode: .common)
        timer = t
    }

    // MARK: Capture

    private func poll() {
        let count = pasteboard.changeCount
        guard count != lastChangeCount else { return }
        lastChangeCount = count
        guard !isPaused else { return }

        let types = pasteboard.types ?? []
        if types.contains(where: { ignoredTypes.contains($0) }) { return }

        let front = NSWorkspace.shared.frontmostApplication
        let name = front?.localizedName
        let bundle = front?.bundleIdentifier

        if let text = pasteboard.string(forType: .string),
           !text.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty {
            add(ClipItem(kind: .text, text: text, sourceName: name, sourceBundleID: bundle))
        } else if let png = pngData(from: pasteboard) {
            let hash = SHA256.hash(data: png).map { String(format: "%02x", $0) }.joined()
            var item = ClipItem(kind: .image, imageHash: hash, sourceName: name, sourceBundleID: bundle)
            if let rep = NSBitmapImageRep(data: png) {
                item.imageSize = "\(rep.pixelsWide)×\(rep.pixelsHigh)"
            }
            if let existing = items.firstIndex(where: { $0.imageHash == hash }) {
                item.imageFile = items[existing].imageFile
            } else {
                let file = "\(item.id.uuidString).png"
                try? png.write(to: imagesURL.appendingPathComponent(file))
                item.imageFile = file
            }
            add(item)
        }
    }

    private func pngData(from pb: NSPasteboard) -> Data? {
        if let png = pb.data(forType: .png) { return png }
        if let tiff = pb.data(forType: .tiff), let rep = NSBitmapImageRep(data: tiff) {
            return rep.representation(using: .png, properties: [:])
        }
        return nil
    }

    private func add(_ new: ClipItem) {
        var item = new
        if let idx = items.firstIndex(where: { isDuplicate($0, new) }) {
            let old = items.remove(at: idx)
            item.pinned = old.pinned
            if old.kind == .image, old.imageFile != item.imageFile, let f = old.imageFile {
                try? FileManager.default.removeItem(at: imagesURL.appendingPathComponent(f))
            }
        }
        items.insert(item, at: 0)
        prune()
        save()
    }

    private func isDuplicate(_ a: ClipItem, _ b: ClipItem) -> Bool {
        guard a.kind == b.kind else { return false }
        return a.kind == .text ? a.text == b.text : a.imageHash == b.imageHash
    }

    private func prune() {
        var unpinned = 0
        var keep: [ClipItem] = []
        for item in items {
            if item.pinned { keep.append(item); continue }
            unpinned += 1
            if unpinned <= maxItems { keep.append(item) } else { deleteFile(of: item) }
        }
        if keep.count != items.count { items = keep }
    }

    // MARK: Actions

    func copyToPasteboard(_ item: ClipItem) {
        pasteboard.clearContents()
        switch item.kind {
        case .text:
            pasteboard.setString(item.text ?? "", forType: .string)
        case .image:
            if let f = item.imageFile, let img = NSImage(contentsOf: imagesURL.appendingPathComponent(f)) {
                pasteboard.writeObjects([img])
            }
        }
        lastChangeCount = pasteboard.changeCount
        if let idx = items.firstIndex(where: { $0.id == item.id }) {
            var moved = items.remove(at: idx)
            moved.date = Date()
            items.insert(moved, at: 0)
            save()
        }
    }

    func togglePin(_ id: UUID) {
        guard let idx = items.firstIndex(where: { $0.id == id }) else { return }
        items[idx].pinned.toggle()
        prune()
        save()
    }

    func delete(_ id: UUID) {
        guard let idx = items.firstIndex(where: { $0.id == id }) else { return }
        deleteFile(of: items[idx])
        items.remove(at: idx)
        save()
    }

    func clearUnpinned() {
        items.filter { !$0.pinned }.forEach(deleteFile(of:))
        items.removeAll { !$0.pinned }
        save()
    }

    private func deleteFile(of item: ClipItem) {
        guard item.kind == .image, let f = item.imageFile else { return }
        // Keep the file if another item still references it.
        if items.contains(where: { $0.id != item.id && $0.imageFile == f }) { return }
        try? FileManager.default.removeItem(at: imagesURL.appendingPathComponent(f))
    }

    // MARK: Persistence

    private func save() {
        guard let data = try? JSONEncoder().encode(items) else { return }
        try? data.write(to: historyURL, options: .atomic)
    }

    private func load() {
        guard let data = try? Data(contentsOf: historyURL),
              let decoded = try? JSONDecoder().decode([ClipItem].self, from: data) else { return }
        items = decoded
    }
}
